class EXPORT_OT_e3dgfx(bpy.types.Operator, ExportHelper):
    """Export 3D assets formatted directly for embedded-3dgfx"""
    bl_idname = "export_scene.e3dgfx"
    bl_label = "Export embedded-3dgfx"
    filename_ext = ".rs"

    filter_glob: StringProperty(default="*.rs;*.e3dm;*.e3dt;*.e3dscene", options={'HIDDEN'})

    export_mode: EnumProperty(
        name="Export Mode",
        description="Select asset pipeline target",
        items=(
            ('STATIC_RS', "Static Mesh (.rs)", "Generates zero-alloc Geometry static slices"),
            ('LOD_RS', "LOD Chain (.rs)", "Generates High/Medium/Low LOD mesh set"),
            ('ANIM_RS', "Vertex Animation (.rs)", "Bakes timeline keyframes into VertexAnimation"),
            ('E3DM_BIN', "Binary Mesh (.e3dm)", "asset_cli compatible quantized binary format"),
            ('SCENE_E3DS', "Scene Container (.e3dscene)", "Packages all selected meshes into chunked container"),
            ('BSP_SECTORS', "BSP / Sectors (.rs)", "Doom/Quake style floor regions and sector definitions"),
        ),
        default='STATIC_RS',
    )

    scale_quant: FloatProperty(
        name="Quantization Scale",
        description="Fixed-point scaling multiplier for .e3dm files",
        default=1024.0,
    )

    export_uvs: BoolProperty(name="Export UVs", default=True)
    export_vnormals: BoolProperty(name="Export Vertex Normals (Smooth)", default=True)
    export_vcolors: BoolProperty(name="Export Vertex Colors", default=False)

    lod_high_dist: FloatProperty(name="LOD High Distance", default=50.0)
    lod_med_dist: FloatProperty(name="LOD Medium Distance", default=100.0)
    lod_med_ratio: FloatProperty(name="LOD Medium Decimate", default=0.5, min=0.05, max=0.95)
    lod_low_ratio: FloatProperty(name="LOD Low Decimate", default=0.2, min=0.01, max=0.8)

    anim_start: IntProperty(name="Start Frame", default=1)
    anim_end: IntProperty(name="End Frame", default=30)
    anim_looping: BoolProperty(name="Looping", default=True)

    def execute(self, context):
        depsgraph = context.evaluated_depsgraph_get()
        active_obj = context.active_object

        if self.export_mode == 'SCENE_E3DS':
            export_scene_chunks(self.filepath, context.selected_objects, depsgraph)
            self.report({'INFO'}, f"Packaged {len(context.selected_objects)} objects into {self.filepath}")
            return {'FINISHED'}

        if self.export_mode == 'BSP_SECTORS':
            export_bsp_sectors_rust(self.filepath, context.selected_objects, depsgraph)
            self.report({'INFO'}, f"Exported {len(context.selected_objects)} sectors to {self.filepath}")
            return {'FINISHED'}

        if not active_obj or active_obj.type != 'MESH':
            self.report({'ERROR'}, "Please select a Mesh object to export.")
            return {'CANCELLED'}

        if self.export_mode == 'STATIC_RS':
            export_static_mesh_rust(
                self.filepath, active_obj, depsgraph,
                export_uvs=self.export_uvs,
                export_vnormals=self.export_vnormals,
                export_vcolors=self.export_vcolors
            )
        elif self.export_mode == 'LOD_RS':
            export_lod_chain_rust(
                self.filepath, active_obj, depsgraph,
                high_dist=self.lod_high_dist,
                med_dist=self.lod_med_dist,
                med_ratio=self.lod_med_ratio,
                low_ratio=self.lod_low_ratio
            )
        elif self.export_mode == 'ANIM_RS':
            fps = context.scene.render.fps
            export_vertex_animation_rust(
                self.filepath, active_obj,
                self.anim_start, self.anim_end, fps,
                looping=self.anim_looping
            )
        elif self.export_mode == 'E3DM_BIN':
            export_as_e3dm(self.filepath, active_obj, depsgraph, scale=self.scale_quant)

        self.report({'INFO'}, f"Successfully exported {active_obj.name} to {self.filepath}")
        return {'FINISHED'}


class E3DGFX_OT_bake_texture(bpy.types.Operator):
    """Bake active material into RGB565 / .e3dt texture"""
    bl_idname = "e3dgfx.bake_texture"
    bl_label = "Bake RGB565 Texture"

    width: EnumProperty(
        name="Width",
        items=[('32', '32', ''), ('64', '64', ''), ('128', '128', ''), ('256', '256', '')],
        default='64',
    )
    height: EnumProperty(
        name="Height",
        items=[('32', '32', ''), ('64', '64', ''), ('128', '128', ''), ('256', '256', '')],
        default='64',
    )
    format_choice: EnumProperty(
        name="Format",
        items=[('E3DT', "Binary (.e3dt)", ""), ('RS', "Rust Source (.rs)", "")],
        default='E3DT',
    )

    def execute(self, context):
        obj = context.active_object
        if not obj or obj.type != 'MESH':
            self.report({'ERROR'}, "Select a Mesh object first.")
            return {'CANCELLED'}

        ext = ".e3dt" if self.format_choice == 'E3DT' else ".rs"
        blend_path = bpy.data.filepath
        out_dir = os.path.dirname(blend_path) if blend_path else os.path.expanduser("~")
        out_file = os.path.join(out_dir, f"{bpy.path.clean_name(obj.name)}_tex{ext}")

        bake_and_export_texture_rgb565(
            out_file, obj,
            width=int(self.width),
            height=int(self.height),
            format_choice=self.format_choice
        )
        self.report({'INFO'}, f"Baked texture saved to {out_file}")
        return {'FINISHED'}


