def export_static_mesh_rust(filepath, obj, depsgraph, export_uvs=True, export_vnormals=True, export_vcolors=False):
    """Exports static mesh as Rust source code with Geometry static arrays."""
    eval_obj, mesh_data, bm = get_evaluated_triangulated_mesh(obj, depsgraph)

    vertices = [f"[{v.co.x:.4f}, {v.co.y:.4f}, {v.co.z:.4f}]" for v in bm.verts]
    faces_indices = [[f.verts[0].index, f.verts[1].index, f.verts[2].index] for f in bm.faces]
    faces_str = [f"[{f[0]}, {f[1]}, {f[2]}]" for f in faces_indices]

    lines = extract_unique_lines(faces_indices)
    lines_str = [f"[{a}, {b}]" for a, b in lines]

    normals = [f"[{f.normal.x:.4f}, {f.normal.y:.4f}, {f.normal.z:.4f}]" for f in bm.faces]
    v_normals = [f"[{v.normal.x:.4f}, {v.normal.y:.4f}, {v.normal.z:.4f}]" for v in bm.verts] if export_vnormals else []

    # UVs
    uv_coords = []
    if export_uvs and bm.loops.layers.uv.active:
        uv_layer = bm.loops.layers.uv.active
        vert_uvs = [mathutils.Vector((0.0, 0.0)) for _ in bm.verts]
        for face in bm.faces:
            for loop in face.loops:
                vert_uvs[loop.vert.index] = loop[uv_layer].uv
        uv_coords = [f"[{uv.x:.4f}, {uv.y:.4f}]" for uv in vert_uvs]

    # Vertex Colors
    v_colors = []
    if export_vcolors and bm.loops.layers.color.active:
        col_layer = bm.loops.layers.color.active
        vert_colors = [(1.0, 1.0, 1.0) for _ in bm.verts]
        for face in bm.faces:
            for loop in face.loops:
                c = loop[col_layer]
                vert_colors[loop.vert.index] = (c[0], c[1], c[2])
        v_colors = [f"Rgb565::new({int(r*31)}, {int(g*63)}, {int(b*31)})" for r, g, b in vert_colors]

    bm.free()
    eval_obj.to_mesh_clear()

    clean_name = bpy.path.clean_name(obj.name).upper()

    with open(filepath, "w") as f:
        f.write("// Auto-generated by embedded-3dgfx Blender Exporter\n")
        f.write("//! Source Object: " + obj.name + "\n\n")
        f.write("use embedded_3dgfx::mesh::Geometry;\n")
        if v_colors:
            f.write("use embedded_graphics_core::pixelcolor::Rgb565;\n")
        f.write("\n")

        f.write(f"pub static {clean_name}_VERTICES: [[f32; 3]; {len(vertices)}] = [\n    " + ",\n    ".join(vertices) + "\n];\n\n")
        f.write(f"pub static {clean_name}_FACES: [[usize; 3]; {len(faces_str)}] = [\n    " + ",\n    ".join(faces_str) + "\n];\n\n")
        f.write(f"pub static {clean_name}_LINES: [[usize; 2]; {len(lines_str)}] = [\n    " + ",\n    ".join(lines_str) + "\n];\n\n")
        f.write(f"pub static {clean_name}_NORMALS: [[f32; 3]; {len(normals)}] = [\n    " + ",\n    ".join(normals) + "\n];\n\n")

        if v_normals:
            f.write(f"pub static {clean_name}_VERTEX_NORMALS: [[f32; 3]; {len(v_normals)}] = [\n    " + ",\n    ".join(v_normals) + "\n];\n\n")
        if uv_coords:
            f.write(f"pub static {clean_name}_UVS: [[f32; 2]; {len(uv_coords)}] = [\n    " + ",\n    ".join(uv_coords) + "\n];\n\n")
        if v_colors:
            f.write(f"pub static {clean_name}_COLORS: [Rgb565; {len(v_colors)}] = [\n    " + ",\n    ".join(v_colors) + "\n];\n\n")

        v_norm_ref = f"&{clean_name}_VERTEX_NORMALS" if v_normals else "&[]"
        uv_ref = f"&{clean_name}_UVS" if uv_coords else "&[]"
        col_ref = f"&{clean_name}_COLORS" if v_colors else "&[]"

        f.write(f"pub static {clean_name}_GEOMETRY: Geometry<'static> = Geometry {{\n")
        f.write(f"    vertices: &{clean_name}_VERTICES,\n")
        f.write(f"    faces: &{clean_name}_FACES,\n")
        f.write(f"    lines: &{clean_name}_LINES,\n")
        f.write(f"    normals: &{clean_name}_NORMALS,\n")
        f.write(f"    vertex_normals: {v_norm_ref},\n")
        f.write(f"    uvs: {uv_ref},\n")
        f.write(f"    colors: {col_ref},\n")
        f.write(f"    texture_id: None,\n")
        f.write("};\n")


