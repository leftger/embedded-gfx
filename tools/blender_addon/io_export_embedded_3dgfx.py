class VIEW3D_PT_e3dgfx_inspector(bpy.types.Panel):
    """Sidebar Panel for embedded-3dgfx Microcontroller Asset Budget & Tools"""
    bl_label = "embedded-3dgfx Studio"
    bl_space_type = 'VIEW_3D'
    bl_region_type = 'UI'
    bl_category = "embedded-3dgfx"

    def draw(self, context):
        layout = self.layout
        obj = context.active_object

        box = layout.box()
        box.label(text="Microcontroller Budget", icon='MEMORY')

        if obj and obj.type == 'MESH':
            mesh = obj.data
            tri_count = sum(len(p.vertices) - 2 for p in mesh.polygons)
            vert_count = len(mesh.vertices)

            box.label(text=f"Selected: {obj.name}", icon='MESH_DATA')
            row = box.row(align=True)
            row.label(text=f"Tris: {tri_count}")
            row.label(text=f"Verts: {vert_count}")

            # ROM / RAM estimates
            rom_geom = (vert_count * 12) + (tri_count * 12) + (tri_count * 12)
            rom_quant = (vert_count * 6) + (tri_count * 6) + 18

            box.label(text=f"ROM (.rs): ~{rom_geom / 1024:.1f} KB")
            box.label(text=f"ROM (.e3dm): ~{rom_quant / 1024:.1f} KB")

            # MCU Compatibility Status
            if tri_count <= 800:
                box.label(text="✓ Cortex-M0+ / M4 / ESP32 (Light)", icon='CHECKMARK')
            elif tri_count <= 3000:
                box.label(text="✓ Cortex-M7 / ESP32-S3 (Medium)", icon='CHECKMARK')
            else:
                box.label(text="⚠️ Heavy for embedded targets!", icon='ERROR')

            layout.separator()
            tools_box = layout.box()
            tools_box.label(text="Quick Tools", icon='TOOL_SETTINGS')
            tools_box.operator("e3dgfx.quick_triangulate", text="Add Triangulate Modifier")
            tools_box.operator("e3dgfx.bake_texture", text="Bake RGB565 Texture")

            layout.separator()
            layout.operator("export_scene.e3dgfx", text="Export Asset / Scene", icon='EXPORT')
        else:
            box.label(text="Select a Mesh object to inspect")


