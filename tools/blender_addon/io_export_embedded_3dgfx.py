def export_vertex_animation_rust(filepath, obj, frame_start, frame_end, fps, looping=True):
    """Samples vertex positions across animation frames and exports a VertexAnimation struct."""
    scene = bpy.context.scene
    clean_name = bpy.path.clean_name(obj.name).upper()
    orig_frame = scene.frame_current

    keyframes_data = []
    base_faces = None
    base_lines = None
    base_normals = None

    try:
        for f in range(frame_start, frame_end + 1):
            scene.frame_set(f)
            depsgraph = bpy.context.evaluated_depsgraph_get()
            eval_obj, mesh_data, bm = get_evaluated_triangulated_mesh(obj, depsgraph)

            verts = [f"[{v.co.x:.4f}, {v.co.y:.4f}, {v.co.z:.4f}]" for v in bm.verts]
            time_sec = (f - frame_start) / float(fps)
            keyframes_data.append((f, time_sec, verts))

            if base_faces is None:
                faces_idx = [[face.verts[0].index, face.verts[1].index, face.verts[2].index] for face in bm.faces]
                base_faces = [f"[{fc[0]}, {fc[1]}, {fc[2]}]" for fc in faces_idx]
                lines = extract_unique_lines(faces_idx)
                base_lines = [f"[{a}, {b}]" for a, b in lines]
                base_normals = [f"[{face.normal.x:.4f}, {face.normal.y:.4f}, {face.normal.z:.4f}]" for face in bm.faces]

            bm.free()
            eval_obj.to_mesh_clear()

    finally:
        scene.frame_set(orig_frame)

    vert_count = len(keyframes_data[0][2])

    with open(filepath, "w") as f:
        f.write("// Auto-generated Vertex Animation by embedded-3dgfx Blender Exporter\n")
        f.write("use embedded_3dgfx::animation::{Keyframe, VertexAnimation};\n")
        f.write("use embedded_3dgfx::mesh::Geometry;\n\n")

        for f_idx, (frame_num, time_sec, verts) in enumerate(keyframes_data):
            f.write(f"static {clean_name}_FRAME_{f_idx}_VERTS: [[f32; 3]; {vert_count}] = [\n    " + ",\n    ".join(verts) + "\n];\n\n")

        f.write(f"pub static {clean_name}_KEYFRAMES: [Keyframe<'static>; {len(keyframes_data)}] = [\n")
        for f_idx, (frame_num, time_sec, _) in enumerate(keyframes_data):
            f.write(f"    Keyframe {{\n")
            f.write(f"        vertices: &{clean_name}_FRAME_{f_idx}_VERTS,\n")
            f.write(f"        time: {time_sec:.4f},\n")
            f.write(f"    }},\n")
        f.write("];\n\n")

        f.write(f"pub static {clean_name}_FACES: [[usize; 3]; {len(base_faces)}] = [\n    " + ",\n    ".join(base_faces) + "\n];\n\n")
        f.write(f"pub static {clean_name}_LINES: [[usize; 2]; {len(base_lines)}] = [\n    " + ",\n    ".join(base_lines) + "\n];\n\n")
        f.write(f"pub static {clean_name}_NORMALS: [[f32; 3]; {len(base_normals)}] = [\n    " + ",\n    ".join(base_normals) + "\n];\n\n")

        loop_str = "true" if looping else "false"
        f.write(f"pub fn create_{clean_name.lower()}_animation() -> VertexAnimation<'static> {{\n")
        f.write(f"    VertexAnimation::new(&{clean_name}_KEYFRAMES, {loop_str})\n")
        f.write("}\n")


