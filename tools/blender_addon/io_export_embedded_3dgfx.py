def export_lod_chain_rust(filepath, obj, depsgraph, high_dist=50.0, med_dist=100.0, med_ratio=0.5, low_ratio=0.25):
    """Exports multi-level LOD geometries and a helper constructor."""
    clean_name = bpy.path.clean_name(obj.name).upper()

    def get_tier_data(decimate_ratio=1.0):
        eval_obj = obj.evaluated_get(depsgraph)
        mesh_data = eval_obj.to_mesh()
        bm = bmesh.new()
        bm.from_mesh(mesh_data)
        bmesh.ops.triangulate(bm, faces=bm.faces[:])
        if decimate_ratio < 0.99:
            bmesh.ops.decimate(bm, faces=bm.faces[:], ptgt=decimate_ratio)
        bm.verts.ensure_lookup_table()
        bm.faces.ensure_lookup_table()

        for v in bm.verts:
            v.co = to_e3d_coords(v.co)
            v.normal = to_e3d_coords(v.normal)
        for f in bm.faces:
            f.normal = to_e3d_coords(f.normal)

        verts = [f"[{v.co.x:.4f}, {v.co.y:.4f}, {v.co.z:.4f}]" for v in bm.verts]
        faces_idx = [[f.verts[0].index, f.verts[1].index, f.verts[2].index] for f in bm.faces]
        faces_str = [f"[{f[0]}, {f[1]}, {f[2]}]" for f in faces_idx]
        lines = extract_unique_lines(faces_idx)
        lines_str = [f"[{a}, {b}]" for a, b in lines]
        normals = [f"[{f.normal.x:.4f}, {f.normal.y:.4f}, {f.normal.z:.4f}]" for f in bm.faces]

        bm.free()
        eval_obj.to_mesh_clear()
        return verts, faces_str, lines_str, normals

    tiers = [
        ("HIGH", 1.0),
        ("MED", med_ratio),
        ("LOW", low_ratio),
    ]

    with open(filepath, "w") as f:
        f.write("// Auto-generated LOD Chain by embedded-3dgfx Blender Exporter\n")
        f.write("use embedded_3dgfx::mesh::{Geometry, K3dMesh, LODLevels};\n\n")

        for suffix, ratio in tiers:
            verts, faces, lines, normals = get_tier_data(ratio)
            f.write(f"pub static {clean_name}_{suffix}_VERTICES: [[f32; 3]; {len(verts)}] = [\n    " + ",\n    ".join(verts) + "\n];\n\n")
            f.write(f"pub static {clean_name}_{suffix}_FACES: [[usize; 3]; {len(faces)}] = [\n    " + ",\n    ".join(faces) + "\n];\n\n")
            f.write(f"pub static {clean_name}_{suffix}_LINES: [[usize; 2]; {len(lines)}] = [\n    " + ",\n    ".join(lines) + "\n];\n\n")
            f.write(f"pub static {clean_name}_{suffix}_NORMALS: [[f32; 3]; {len(normals)}] = [\n    " + ",\n    ".join(normals) + "\n];\n\n")

            f.write(f"pub static {clean_name}_{suffix}_GEOMETRY: Geometry<'static> = Geometry {{\n")
            f.write(f"    vertices: &{clean_name}_{suffix}_VERTICES,\n")
            f.write(f"    faces: &{clean_name}_{suffix}_FACES,\n")
            f.write(f"    lines: &{clean_name}_{suffix}_LINES,\n")
            f.write(f"    normals: &{clean_name}_{suffix}_NORMALS,\n")
            f.write(f"    vertex_normals: &[],\n")
            f.write(f"    uvs: &[],\n")
            f.write(f"    colors: &[],\n")
            f.write(f"    texture_id: None,\n")
            f.write("};\n\n")

        f.write(f"pub fn create_{clean_name.lower()}_lod_mesh() -> K3dMesh<'static> {{\n")
        f.write(f"    let mut mesh = K3dMesh::new({clean_name}_HIGH_GEOMETRY);\n")
        f.write(f"    mesh.set_lod(\n")
        f.write(f"        Some({clean_name}_MED_GEOMETRY),\n")
        f.write(f"        Some({clean_name}_LOW_GEOMETRY),\n")
        f.write(f"        LODLevels {{\n")
        f.write(f"            high_distance: {high_dist:.1f},\n")
        f.write(f"            medium_distance: {med_dist:.1f},\n")
        f.write(f"            #[cfg(feature = \"lod-crossfade\")]\n")
        f.write(f"            fade_margin: 0.0,\n")
        f.write(f"        }},\n")
        f.write(f"    );\n")
        f.write(f"    mesh\n")
        f.write("}\n")


