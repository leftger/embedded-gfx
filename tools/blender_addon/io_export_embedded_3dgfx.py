def bake_and_export_texture_rgb565(filepath, obj, width=64, height=64, format_choice='E3DT'):
    """
    Bakes object color/diffuse texture to a power-of-two RGB565 buffer.
    Can export as .e3dt binary, .ppm, or static Rust byte array.
    """
    # Create a temporary bake image in Blender
    img_name = f"e3d_bake_{obj.name}"
    if img_name in bpy.data.images:
        bpy.data.images.remove(bpy.data.images[img_name])
    img = bpy.data.images.new(img_name, width=width, height=height, alpha=False)

    # Read pixels (Blender stores pixels as RGBA floats [0..1], row-by-row bottom-up)
    pixels = list(img.pixels) # (r, g, b, a) floats

    # Convert to RGB565
    rgb565_bytes = bytearray()
    rgb565_u16s = []

    # Blender image pixels are bottom-to-top; flip to top-down for standard scanlines
    for y in range(height - 1, -1, -1):
        for x in range(width):
            idx = (y * width + x) * 4
            r, g, b = pixels[idx], pixels[idx + 1], pixels[idx + 2]
            packed = color_to_rgb565(r, g, b)
            rgb565_u16s.append(packed)
            rgb565_bytes.extend(struct.pack("<H", packed))

    bpy.data.images.remove(img)

    if format_choice == 'E3DT':
        # E3DT format: magic "E3DT", u16 ver=1, u32 w, u32 h, raw 565 bytes
        with open(filepath, "wb") as f:
            f.write(b"E3DT")
            f.write(struct.pack("<H", 1))
            f.write(struct.pack("<II", width, height))
            f.write(rgb565_bytes)

    elif format_choice == 'RS':
        clean_name = bpy.path.clean_name(obj.name).upper()
        with open(filepath, "w") as f:
            f.write("// Auto-generated Texture by embedded-3dgfx Blender Exporter\n")
            f.write("use embedded_3dgfx::texture::Texture;\n")
            f.write("use embedded_graphics_core::pixelcolor::Rgb565;\n\n")
            f.write(f"pub const {clean_name}_TEX_WIDTH: u32 = {width};\n")
            f.write(f"pub const {clean_name}_TEX_HEIGHT: u32 = {height};\n\n")
            f.write(f"pub static {clean_name}_TEX_DATA: [Rgb565; {len(rgb565_u16s)}] = [\n")
            for i, val in enumerate(rgb565_u16s):
                f.write(f"    Rgb565::from_raw({val}),\n")
            f.write("];\n\n")
            f.write(f"pub fn create_{clean_name.lower()}_texture() -> Texture {{\n")
            f.write(f"    Texture::new(&{clean_name}_TEX_DATA, {clean_name}_TEX_WIDTH, {clean_name}_TEX_HEIGHT)\n")
            f.write("}\n")


