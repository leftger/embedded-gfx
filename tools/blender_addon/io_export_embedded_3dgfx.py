def to_e3d_coords(vec):
    """Convert Blender (Z-up, right-handed) to embedded-3dgfx (Y-up, right-handed): (x, y, z) -> (x, z, -y)"""
    return mathutils.Vector((vec.x, vec.z, -vec.y))


def color_to_rgb565(r_f, g_f, b_f):
    """Convert float RGB [0.0, 1.0] to packed RGB565 u16."""
    r5 = int(round(max(0.0, min(1.0, r_f)) * 31.0)) & 0x1F
    g6 = int(round(max(0.0, min(1.0, g_f)) * 63.0)) & 0x3F
    b5 = int(round(max(0.0, min(1.0, b_f)) * 31.0)) & 0x1F
    return (r5 << 11) | (g6 << 5) | b5


def get_evaluated_triangulated_mesh(obj, depsgraph, apply_modifiers=True, transform_coords=True):
    """
    Evaluates modifiers and returns a triangulated BMesh.
    Returns: (eval_obj, mesh_data, bm)
    """
    if apply_modifiers:
        eval_obj = obj.evaluated_get(depsgraph)
    else:
        eval_obj = obj

    mesh_data = eval_obj.to_mesh()
    bm = bmesh.new()
    bm.from_mesh(mesh_data)

    # Triangulate all faces
    bmesh.ops.triangulate(bm, faces=bm.faces[:])
    bm.verts.ensure_lookup_table()
    bm.faces.ensure_lookup_table()

    if transform_coords:
        for v in bm.verts:
            v.co = to_e3d_coords(v.co)
            v.normal = to_e3d_coords(v.normal)
        for f in bm.faces:
            f.normal = to_e3d_coords(f.normal)

    return eval_obj, mesh_data, bm


def extract_unique_lines(faces):
    """Generates unique sorted edges (min, max) from triangular faces."""
    edge_set = set()
    for f in faces:
        for a, b in [(f[0], f[1]), (f[1], f[2]), (f[2], f[0])]:
            edge_set.add((min(a, b), max(a, b)))
    return sorted(list(edge_set))


