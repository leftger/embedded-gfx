# BSP / Sector Level Exporter (Retro Doom / Quake Style)
# ============================================================================

def export_bsp_sectors_rust(filepath, selected_objects, depsgraph):
    """Exports polygon boundary loops, sector heights, and floor regions for retro engines."""
    sectors_data = []

    for obj in selected_objects:
        if obj.type != 'MESH':
            continue
        eval_obj, mesh_data, bm = get_evaluated_triangulated_mesh(obj, depsgraph)

        floor_z = min(v.co.y for v in bm.verts) # In E3D Y is up
        ceil_z = max(v.co.y for v in bm.verts)

        # Extract 2D boundary vertices (X, Z plane)
        poly_points = [f"[{v.co.x:.2f}, {v.co.z:.2f}]" for v in bm.verts]
        sectors_data.append((obj.name, floor_z, ceil_z, poly_points))

        bm.free()
        eval_obj.to_mesh_clear()

    with open(filepath, "w") as f:
        f.write("// Auto-generated BSP Sector Map by embedded-3dgfx Blender Exporter\n\n")
        f.write("#[derive(Debug, Clone, Copy)]\n")
        f.write("pub struct SectorDef<'a> {\n")
        f.write("    pub name: &'static str,\n")
        f.write("    pub floor_height: f32,\n")
        f.write("    pub ceiling_height: f32,\n")
        f.write("    pub polygon_2d: &'a [[f32; 2]],\n")
        f.write("}\n\n")

        for idx, (name, f_h, c_h, pts) in enumerate(sectors_data):
            f.write(f"static SECTOR_{idx}_PTS: [[f32; 2]; {len(pts)}] = [\n    " + ",\n    ".join(pts) + "\n];\n\n")

        f.write(f"pub static WORLD_SECTORS: [SectorDef<'static>; {len(sectors_data)}] = [\n")
        for idx, (name, f_h, c_h, pts) in enumerate(sectors_data):
            f.write(f"    SectorDef {{\n")
            f.write(f"        name: \"{name}\",\n")
            f.write(f"        floor_height: {f_h:.2f},\n")
            f.write(f"        ceiling_height: {c_h:.2f},\n")
            f.write(f"        polygon_2d: &SECTOR_{idx}_PTS,\n")
            f.write(f"    }},\n")
        f.write("];\n")


