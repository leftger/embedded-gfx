def build_e3dm_bytes(obj, depsgraph, scale=1024.0):
    """Encodes active mesh as .e3dm byte payload."""
    eval_obj, mesh_data, bm = get_evaluated_triangulated_mesh(obj, depsgraph)

    verts_q = []
    for v in bm.verts:
        verts_q.append((
            int(round(v.co.x * scale)),
            int(round(v.co.y * scale)),
            int(round(v.co.z * scale)),
        ))

    faces = [(f.verts[0].index, f.verts[1].index, f.verts[2].index) for f in bm.faces]

    bm.free()
    eval_obj.to_mesh_clear()

    out = bytearray()
    out.extend(b"E3DM")
    out.extend(struct.pack("<H", 1)) # version 1
    out.extend(struct.pack("<II", len(verts_q), len(faces)))
    out.extend(struct.pack("<f", scale))

    for vx, vy, vz in verts_q:
        out.extend(struct.pack("<hhh", vx, vy, vz))
    for i0, i1, i2 in faces:
        out.extend(struct.pack("<HHH", i0, i1, i2))

    return bytes(out)


def export_as_e3dm(filepath, obj, depsgraph, scale=1024.0):
    """Writes quantized binary format (.e3dm) to file."""
    data = build_e3dm_bytes(obj, depsgraph, scale)
    with open(filepath, "wb") as f:
        f.write(data)


def export_scene_chunks(filepath, selected_objects, depsgraph):
    """Packs multiple selected meshes into an E3DS chunked scene container."""
    chunks = []

    for obj in selected_objects:
        if obj.type != 'MESH':
            continue
        mesh_bytes = build_e3dm_bytes(obj, depsgraph, scale=1024.0)
        # kind = 1 (Mesh)
        chunks.append((1, mesh_bytes))

    out = bytearray()
    out.extend(b"E3DS")
    out.extend(struct.pack("<H", 1)) # Version 1
    out.extend(struct.pack("<H", len(chunks)))

    for kind, payload in chunks:
        out.extend(struct.pack("<HI", kind, len(payload)))
        out.extend(payload)

    with open(filepath, "wb") as f:
        f.write(out)


